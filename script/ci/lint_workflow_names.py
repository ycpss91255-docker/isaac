#!/usr/bin/env python3
"""Lint GitHub Actions workflow / job names against the naming rule (isaac#443).

The rule is written in doc/workflow-naming.md. In short:

* file   `<category>-<feature>.yaml`, category one of ci / release / bot / tool,
         feature kebab-case;
* name   `<Category>: <Feature Words>`, e.g. `ci-stream-smoke.yaml` is
         `CI: Stream Smoke`;
* jobs   kebab-case ids, no job-level `name:` (the check name is the job id).
         In CI workflows (`main.yaml`, `ci-*.yaml`) an id is `changes`, `gate`,
         `release` or starts with a scope group (core- gui- stream- headless-
         docs-).

Files base's init.sh owns are exempt by exact name (EXEMPT_FILES, each with its
reason). The lint also fails when the documentation still mentions a workflow
or job name the rule retired (RETIRED_NAMES).

Usage: lint_workflow_names.py [repo-root]   (exit 1 and list every violation)
"""

import re
import sys
from pathlib import Path

import yaml

CATEGORIES = {"ci": "CI", "release": "Release", "bot": "Bot", "tool": "Tool"}
GROUPS = ("core", "gui", "stream", "headless", "docs")
CI_FREE_JOBS = ("changes", "gate", "release")

# Exempt from the file-name and display-name rules, by exact file name. Their
# jobs still follow the job rule, except where the reason says otherwise.
EXEMPT_FILES = {
    "main.yaml": (
        "The org-wide entry workflow: every ycpss91255-docker repo has a "
        "main.yaml and base's init.sh creates it. It carries both CI and "
        "release, so it has no single category."
    ),
    "base-version-monitor.yaml": (
        "Generated by base's init.sh (_sync_base_monitor_workflow), which "
        "creates exactly this path when it is absent: a renamed file is "
        "regenerated beside the renamed one on the next base upgrade. Kept "
        "under its original name and content."
    ),
    "publish-stream-source.yaml": (
        "Removed in isaac#432 (the producer image moves out); not worth "
        "renaming first."
    ),
}
# Fully exempt, jobs included (the file is going away).
_FULLY_EXEMPT = {"publish-stream-source.yaml"}

_FILE_RE = re.compile(
    r"^(?P<category>ci|release|bot|tool)-(?P<feature>[a-z0-9]+(?:-[a-z0-9]+)*)\.yaml$"
)
_KEBAB_RE = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
_GROUP_JOB_RE = re.compile(r"^(?:%s)-[a-z0-9]+(?:-[a-z0-9]+)*$" % "|".join(GROUPS))

# Names the rule retired; the docs must not mention them.
RETIRED_NAMES = (
    ("call-docker-build", re.compile(r"call-docker-build")),
    ("call-release", re.compile(r"call-release")),
    ("stream-smoke.yaml", re.compile(r"(?<![\w-])stream-smoke\.yaml")),
    ("Stream Smoke (GPU)", re.compile(r"Stream Smoke \(GPU\)")),
)
# Documents that scan for retired names. History (changelog, ADRs) is not
# scanned, and the rule document itself records the renames.
_DOC_GLOBS = ("README*.md", "doc/*.md", "doc/test/*.md")
_DOC_SKIP = {"doc/workflow-naming.md"}


def workflow_files(root):
    return sorted((Path(root) / ".github" / "workflows").glob("*.y*ml"))


def _title(feature):
    return " ".join(word.capitalize() for word in feature.split("-"))


def _is_ci(filename):
    return filename == "main.yaml" or filename.startswith("ci-")


def _lint_file(path):
    errors = []
    filename = path.name
    if filename in _FULLY_EXEMPT:
        return errors
    doc = yaml.safe_load(path.read_text()) or {}

    if filename not in EXEMPT_FILES:
        match = _FILE_RE.match(filename)
        if not match:
            errors.append(
                f"{filename}: file name must be <category>-<feature>.yaml "
                f"(category one of {', '.join(CATEGORIES)}; kebab-case; .yaml)"
            )
        else:
            expected = f"{CATEGORIES[match['category']]}: {_title(match['feature'])}"
            if doc.get("name") != expected:
                errors.append(
                    f"{filename}: name must be {expected!r}, got {doc.get('name')!r}"
                )

    for job_id, job in (doc.get("jobs") or {}).items():
        if not _KEBAB_RE.match(job_id):
            errors.append(f"{filename}: job id {job_id!r} must be kebab-case")
        elif _is_ci(filename) and job_id not in CI_FREE_JOBS and not _GROUP_JOB_RE.match(job_id):
            errors.append(
                f"{filename}: CI job id {job_id!r} must be one of "
                f"{', '.join(CI_FREE_JOBS)} or start with a group "
                f"({', '.join(g + '-' for g in GROUPS)})"
            )
        if isinstance(job, dict) and "name" in job:
            errors.append(
                f"{filename}: job {job_id!r} sets name:; omit it so the check "
                "name is the job id"
            )
    return errors


def stale_references(root):
    """One error per retired name found in the scanned documents."""
    errors = []
    root = Path(root)
    seen = set()
    for pattern in _DOC_GLOBS:
        for path in sorted(root.glob(pattern)):
            rel = path.relative_to(root).as_posix()
            if rel in _DOC_SKIP or rel in seen:
                continue
            seen.add(rel)
            text = path.read_text()
            for label, regex in RETIRED_NAMES:
                for match in regex.finditer(text):
                    line = text.count("\n", 0, match.start()) + 1
                    errors.append(f"{rel}:{line}: retired name {label!r}")
    return errors


def lint(root):
    errors = []
    for path in workflow_files(root):
        errors.extend(_lint_file(path))
    errors.extend(stale_references(root))
    return errors


def main(argv):
    root = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parents[2]
    errors = lint(root)
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    print("OK: workflow names follow doc/workflow-naming.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
